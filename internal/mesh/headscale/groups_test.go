package headscale

import (
	"strings"
	"testing"

	"github.com/minihci/tink/internal/identity"
)

func labSnapshot() identity.Snapshot {
	return identity.Snapshot{Groups: []identity.Group{
		{Name: "lldap_admin", System: true, Members: []identity.Person{{ID: "admin"}}},
		{Name: "family", Members: []identity.Person{
			{ID: "bob", Email: "bob@lab.test"}, {ID: "alice", Email: "alice@lab.test"}}},
		{Name: "admins", Members: []identity.Person{{ID: "alice", Email: "alice@lab.test"}}},
		{Name: "kids"},
	}}
}

func findings(r Result) string {
	var s []string
	for _, f := range r.Findings {
		s = append(s, f.String())
	}
	return strings.Join(s, "\n")
}

func TestProject_NamedGroupsAreDeterministicAndSorted(t *testing.T) {
	res := Project(labSnapshot(), Options{Groups: []string{"family", "admins"}})
	if res.HasErrors() || len(res.Findings) != 0 {
		t.Fatalf("unexpected findings: %s", findings(res))
	}
	want := `// generated by tink from the directory; do not edit by hand
"groups": {
  "group:admins": ["alice@"],
  "group:family": ["alice@", "bob@"],
},
`
	if res.Text != want {
		t.Errorf("fragment =\n%s\nwant\n%s", res.Text, want)
	}
}

func TestProject_TheSameDirectoryInAnyOrderGivesTheSameBytes(t *testing.T) {
	a := labSnapshot()
	b := identity.Snapshot{Groups: []identity.Group{a.Groups[3], a.Groups[2], a.Groups[1], a.Groups[0]}}
	b.Groups[2].Members = []identity.Person{b.Groups[2].Members[1], b.Groups[2].Members[0]}
	o := Options{Groups: []string{"admins", "family"}}
	if Project(a, o).Text != Project(b, o).Text {
		t.Error("the output depends on the order of the input")
	}
}

func TestProject_NoGroupsNamedMeansEverySiteGroupAndNeverTheSystemOnes(t *testing.T) {
	res := Project(labSnapshot(), Options{})
	if strings.Contains(res.Text, "lldap_admin") {
		t.Errorf("a system group was emitted:\n%s", res.Text)
	}
	for _, want := range []string{`"group:admins"`, `"group:family"`, `"group:kids": []`} {
		if !strings.Contains(res.Text, want) {
			t.Errorf("fragment is missing %s:\n%s", want, res.Text)
		}
	}
}

func TestProject_AGroupWithNoMembersIsEmittedEmptyWithAWarning(t *testing.T) {
	res := Project(labSnapshot(), Options{Groups: []string{"kids"}})
	if res.HasErrors() {
		t.Fatalf("an empty group is a warning, not an error: %s", findings(res))
	}
	if !strings.Contains(res.Text, `"group:kids": [],`) {
		t.Errorf("empty group not emitted:\n%s", res.Text)
	}
	if !strings.Contains(findings(res), `warning: group "kids" has no members`) {
		t.Errorf("findings = %q", findings(res))
	}
}

func TestProject_AMissingGroupIsAnErrorAndProducesNoFragment(t *testing.T) {
	res := Project(labSnapshot(), Options{Groups: []string{"family", "nope"}})
	if !res.HasErrors() || res.Text != "" {
		t.Fatalf("want an error and no text, got text %q findings %s", res.Text, findings(res))
	}
	if !strings.Contains(findings(res), `error: group "nope" is not in the directory`) {
		t.Errorf("findings = %q", findings(res))
	}
}

func TestProject_EmailFormat(t *testing.T) {
	res := Project(labSnapshot(), Options{Groups: []string{"admins"}, MemberFormat: "{email}"})
	if res.HasErrors() || !strings.Contains(res.Text, `"group:admins": ["alice@lab.test"]`) {
		t.Fatalf("text %q findings %s", res.Text, findings(res))
	}
}

func TestProject_BadMemberFormats(t *testing.T) {
	for format, want := range map[string]string{
		"{name}@":  "placeholder other than",
		"fixed":    "no {id} or {email}",
		"{id}@{x}": "placeholder other than",
		"{id@":     "placeholder other than",
	} {
		res := Project(labSnapshot(), Options{Groups: []string{"admins"}, MemberFormat: format})
		if !res.HasErrors() || res.Text != "" || !strings.Contains(findings(res), want) {
			t.Errorf("format %q: text %q findings %q, want an error mentioning %q", format, res.Text, findings(res), want)
		}
	}
}

func TestProject_APersonWithoutAnEmailCannotBeWrittenAsOne(t *testing.T) {
	s := identity.Snapshot{Groups: []identity.Group{{Name: "g", Members: []identity.Person{{ID: "admin"}}}}}
	res := Project(s, Options{Groups: []string{"g"}, MemberFormat: "{email}"})
	if !res.HasErrors() || !strings.Contains(findings(res), `person "admin" has no email`) {
		t.Fatalf("findings = %q", findings(res))
	}
}

func TestProject_TwoPeopleWithTheSameNameAreAnError(t *testing.T) {
	s := identity.Snapshot{Groups: []identity.Group{{Name: "g", Members: []identity.Person{
		{ID: "a", Email: "same@x"}, {ID: "b", Email: "same@x"}}}}}
	res := Project(s, Options{Groups: []string{"g"}, MemberFormat: "{email}"})
	if !res.HasErrors() || !strings.Contains(findings(res), "would both be written as") {
		t.Fatalf("findings = %q", findings(res))
	}
}

func TestProject_AGroupNameThePolicyCannotUseIsReportedNotRewritten(t *testing.T) {
	s := identity.Snapshot{Groups: []identity.Group{{Name: "my group", Members: []identity.Person{{ID: "a"}}}}}
	res := Project(s, Options{Groups: []string{"my group"}})
	if !res.HasErrors() || !strings.Contains(findings(res), `"my group" cannot be used`) {
		t.Fatalf("findings = %q", findings(res))
	}
}

func TestProject_OnlySystemGroupsMeansAnEmptyBlockAndAWarning(t *testing.T) {
	s := identity.Snapshot{Groups: []identity.Group{{Name: "lldap_admin", System: true}}}
	res := Project(s, Options{})
	if res.HasErrors() || !strings.Contains(res.Text, `"groups": {},`) || !strings.Contains(findings(res), "nothing to emit") {
		t.Fatalf("text %q findings %q", res.Text, findings(res))
	}
}

func TestProject_QuotingDoesNotEscapeHTMLCharacters(t *testing.T) {
	s := identity.Snapshot{Groups: []identity.Group{{Name: "g", Members: []identity.Person{{ID: "a", Email: "a+b&c@x"}}}}}
	res := Project(s, Options{Groups: []string{"g"}, MemberFormat: "{email}"})
	if !strings.Contains(res.Text, `"a+b&c@x"`) {
		t.Errorf("the member was escaped:\n%s", res.Text)
	}
}
