// Package authz turns a table of what the daemon is allowed to do into the Starlark authorization scriptlet that Incus runs for its certificate.
//
// The daemon runs under one certificate, and by default Incus trusts an unrestricted certificate with the whole server. This package makes that certificate
// narrow without touching anyone else: the scriptlet is routed for the class `tls` (authorization.client.tls: scriptlet), gives the daemon's fingerprint
// exactly the rules in the table, and judges every other client as Incus's own built-in routing does (an unrestricted TLS client and an OIDC client are
// allowed, anything else is not). Nothing else changes, so a bug in the table cannot narrow, or widen, anyone but the identities it names. The local Unix
// socket never reaches the scriptlet, so the way back is always open from the host.
//
// The text it generates is a function of the table and of the Incus version's shape, nothing else, and is deterministic: the same table always gives the same
// bytes, so installing it twice changes nothing. It is only ever replaced when it starts with Marker, so a scriptlet someone else wrote is never overwritten.
//
// What an identity needs is measured, not guessed (#272 and #252): the rules in DaemonRules are the (object, entitlement) pairs the daemon was asked for on
// Incus 7.5.1, and Check (the command that applies this) makes real requests before and after, because the shape of the scriptlet's `details` argument has
// changed between Incus versions with no changelog entry and a wrong field path shows only when a request is made.
package authz

import (
	"fmt"
	"regexp"
	"sort"
	"strings"
)

// Marker is the first line of every scriptlet this package generates. tink replaces a scriptlet only when it starts with it.
const Marker = "# tink-authz: generated by tink; do not edit, it is rewritten whole"

// Rule is one thing an identity may do: an entitlement on an object. Object is the object exactly as Incus names it ("storage_volume:project/pool/custom/name"),
// or, when Prefix is set, the start of an object, so that "instance:" is every instance and "storage_volume:p/pool/custom/db-bk-" is every restore point of db.
type Rule struct {
	Object      string
	Entitlement string
	Prefix      bool
}

// Identity is a certificate and what it may do. Fingerprint is the certificate's SHA-256, as Incus shows it in `incus config trust list` and passes to the
// scriptlet as details.Username.
type Identity struct {
	Name        string // for a comment in the script and for messages; not part of any decision
	Fingerprint string
	Rules       []Rule
}

// Shape is how one Incus version hands the request to the scriptlet. The script reads the certificate's fingerprint and the authentication protocol through
// these expressions, so a version that moves them is one more Shape and not a second generator.
type Shape struct {
	Name     string
	Username string // an expression for the fingerprint
	Protocol string // an expression for "tls", "oidc", ...
}

// Incus75 is the shape measured on Incus 7.5.1: `details` is flat. (7.4 nested the protocol under details.RequestDetails; it is not generated for.)
var Incus75 = Shape{Name: "incus-7.5", Username: "details.Username", Protocol: "details.Protocol"}

var (
	fingerprintRE = regexp.MustCompile(`^[0-9a-f]{64}$`)
	entitlementRE = regexp.MustCompile(`^can_[a-z_]+$`)
)

// bad is what may not appear inside a quoted string of the script: a quote or backslash would end or alter it, and a control character would break its line.
func bad(r rune) bool { return r == '"' || r == '\\' || r < 0x20 || r == 0x7f }

func (r Rule) validate() error {
	if r.Object == "" || !strings.Contains(r.Object, ":") || strings.IndexFunc(r.Object, bad) >= 0 || strings.ContainsAny(r.Object, " \t") {
		return fmt.Errorf("rule object %q is not an Incus object (type:identifier, with no space, quote, backslash or control character)", r.Object)
	}
	if !entitlementRE.MatchString(r.Entitlement) {
		return fmt.Errorf("rule entitlement %q is not an Incus entitlement (can_...)", r.Entitlement)
	}
	return nil
}

// Generate renders the scriptlet for the identities, in the shape of one Incus version. It refuses anything that would write a script that does not say what
// the table says: a fingerprint that is not a SHA-256, two identities with one fingerprint, an identity with no rule (that would deny it everything, which is
// a decision to write down and not a table that lost its rows), or a rule that cannot be quoted.
func Generate(ids []Identity, shape Shape) (string, error) {
	if shape.Username == "" || shape.Protocol == "" {
		return "", fmt.Errorf("the shape %q does not say where the fingerprint and the protocol are", shape.Name)
	}
	seen := map[string]string{}
	sorted := append([]Identity(nil), ids...)
	for _, id := range sorted {
		if !fingerprintRE.MatchString(id.Fingerprint) {
			return "", fmt.Errorf("identity %q: %q is not a certificate fingerprint (64 lower case hex digits)", id.Name, id.Fingerprint)
		}
		if prev, dup := seen[id.Fingerprint]; dup {
			return "", fmt.Errorf("identities %q and %q have one fingerprint", prev, id.Name)
		}
		seen[id.Fingerprint] = id.Name
		if len(id.Rules) == 0 {
			return "", fmt.Errorf("identity %q has no rules: it would be refused everything", id.Name)
		}
		if strings.ContainsAny(id.Name, "\r\n") {
			return "", fmt.Errorf("identity name %q has a line break", id.Name)
		}
		for _, r := range id.Rules {
			if err := r.validate(); err != nil {
				return "", fmt.Errorf("identity %q: %w", id.Name, err)
			}
		}
	}
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Fingerprint < sorted[j].Fingerprint })

	var b strings.Builder
	b.WriteString(Marker + "\n")
	fmt.Fprintf(&b, "# shape: %s\n", shape.Name)
	b.WriteString(`#
# Route it with: authorization.client.tls: scriptlet. It is run for unrestricted TLS clients only (the local Unix socket never reaches it).
# A fingerprint listed below is held to its rules and to nothing else. Every other client is judged as Incus's own routing judges it without
# this script: an unrestricted TLS client and an OIDC client are allowed, anything else is not.
`)
	b.WriteString("IDENTITIES = {\n")
	for _, id := range sorted {
		exact, prefix := splitRules(id.Rules)
		fmt.Fprintf(&b, "    # %s\n", singleLine(id.Name))
		fmt.Fprintf(&b, "    %q: {\n", id.Fingerprint)
		writeList(&b, "exact", exact)
		writeList(&b, "prefix", prefix)
		b.WriteString("    },\n")
	}
	b.WriteString("}\n\n")
	fmt.Fprintf(&b, `def authorize(details, object, entitlement):
    rules = IDENTITIES.get(%s)
    if rules == None:
        return %s == "tls" or %s == "oidc"
    for r in rules["exact"]:
        if object == r[0] and entitlement == r[1]:
            return True
    for r in rules["prefix"]:
        if object.startswith(r[0]) and entitlement == r[1]:
            return True
    return False
`, shape.Username, shape.Protocol, shape.Protocol)
	return b.String(), nil
}

func singleLine(s string) string {
	return strings.TrimSpace(strings.NewReplacer("\r", " ", "\n", " ").Replace(s))
}

// splitRules sorts the rules and drops repeats, exact first and prefix second.
func splitRules(rules []Rule) (exact, prefix []Rule) {
	seen := map[Rule]bool{}
	for _, r := range rules {
		if seen[r] {
			continue
		}
		seen[r] = true
		if r.Prefix {
			prefix = append(prefix, r)
		} else {
			exact = append(exact, r)
		}
	}
	for _, l := range [][]Rule{exact, prefix} {
		l := l
		sort.Slice(l, func(i, j int) bool {
			if l[i].Object != l[j].Object {
				return l[i].Object < l[j].Object
			}
			return l[i].Entitlement < l[j].Entitlement
		})
	}
	return exact, prefix
}

func writeList(b *strings.Builder, name string, rules []Rule) {
	if len(rules) == 0 {
		fmt.Fprintf(b, "        %q: [],\n", name)
		return
	}
	fmt.Fprintf(b, "        %q: [\n", name)
	for _, r := range rules {
		fmt.Fprintf(b, "            (%q, %q),\n", r.Object, r.Entitlement)
	}
	b.WriteString("        ],\n")
}

// IsOurs says whether a scriptlet is one this package generated, and so one tink may replace.
func IsOurs(scriptlet string) bool { return strings.HasPrefix(scriptlet, Marker) }
