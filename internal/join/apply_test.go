// A file tink did not write may hold records written by hand; the first run on a real platform meets exactly that.
func TestApplyDNSRefusesToOverwriteAFileTinkDidNotWriteUnlessAdopted(t *testing.T) {
	f := platformFiles()
	f.files["tink/dns/hosts"] = "# by hand\n192.0.2.231 auth.home.example.org\n192.0.2.230 canary.home.example.org\n"
	_, err := ApplyDNS(f, canaryResult(t), ApplyOptions{})
	if err == nil || !strings.Contains(err.Error(), "was not written by tink") || !strings.Contains(err.Error(), "2 record(s)") || !strings.Contains(err.Error(), "--adopt") {
		t.Fatalf("err = %v", err)
	}
	if len(f.writes) != 0 {
		t.Error("nothing may be written")
	}
	if _, err := ApplyDNS(f, canaryResult(t), ApplyOptions{DryRun: true}); err == nil {
		t.Error("even a dry run should say the file is not tink's")
	}
	rep, err := ApplyDNS(f, canaryResult(t), ApplyOptions{Adopt: true})
	if err != nil {
		t.Fatal(err)
	}
	if !rep.Written || len(rep.Removed) != 2 || f.files["tink/dns/hosts"] != wantFile {
		t.Errorf("report = %+v, file %q", rep, f.files["tink/dns/hosts"])
	}
}
