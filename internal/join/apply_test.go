// fakeFiles is an instance file API in memory that remembers what was read and written.
type fakeFiles struct {
	files    map[string]string // key: project/instance/path
	reads    []string
	writes   []string
	readErr  map[string]error // by path
	writeErr error
	corrupt  bool // a write that silently does not take
}

func newFakeFiles() *fakeFiles {
	return &fakeFiles{files: map[string]string{}, readErr: map[string]error{}}
}

func fkey(p, i, path string) string { return p + "/" + i + path }

func (f *fakeFiles) Read(p, i, path string) (string, bool, error) {
	f.reads = append(f.reads, path)
	if err := f.readErr[path]; err != nil {
		return "", false, err
	}
	c, ok := f.files[fkey(p, i, path)]
	return c, ok, nil
}

func (f *fakeFiles) Write(p, i, path, content string) error {
	if f.writeErr != nil {
		return f.writeErr
	}
	f.writes = append(f.writes, path)
	if !f.corrupt {
		f.files[fkey(p, i, path)] = content
	}
	return nil
}

const labZone = `; the zone
$ORIGIN home.example.org.
$TTL 30
@   IN SOA ns.home.example.org. hostmaster.home.example.org. (
        1 3600 600 86400 30 )
@   IN NS  ns.home.example.org.
ns  IN A   192.0.2.230
auth IN A  192.0.2.231 ; the portal
id.home.example.org. IN A 192.0.2.231
`

func platformFiles() *fakeFiles {
	f := newFakeFiles()
	f.files["tink/dns/db.home.example.org"] = labZone
	return f
}

func canaryResult(t *testing.T) Result {
	t.Helper()
	res := Build(load(t))
	if res.Errors() != 0 {
		t.Fatal(res.Findings)
	}
	return res
}

const wantFile = "# Generated by `tink join apply dns` from the publish documents. Do not edit: the next run rewrites this file whole.\n" +
	"192.0.2.231 whoami.home.example.org\n192.0.2.231 whoami-admin.home.example.org\n"

func TestApplyDNSCreatesTheFileAndReportsTheRecords(t *testing.T) {
	f := platformFiles()
	rep, err := ApplyDNS(f, canaryResult(t), ApplyOptions{})
	if err != nil {
		t.Fatal(err)
	}
	if !rep.Created || !rep.Changed || !rep.Written || rep.Project != "tink" || rep.Instance != "dns" || rep.Path != "/hosts" {
		t.Errorf("report = %+v", rep)
	}
	if got := f.files["tink/dns/hosts"]; got != wantFile {
		t.Errorf("file =\n%s\nwant\n%s", got, wantFile)
	}
	if strings.Join(rep.Added, "|") != "192.0.2.231 whoami-admin.home.example.org|192.0.2.231 whoami.home.example.org" || len(rep.Removed) != 0 {
		t.Errorf("added %v removed %v", rep.Added, rep.Removed)
	}
}

func TestApplyDNSChangesNothingWhenTheFileIsAlreadyRight(t *testing.T) {
	f := platformFiles()
	f.files["tink/dns/hosts"] = wantFile
	rep, err := ApplyDNS(f, canaryResult(t), ApplyOptions{})
	if err != nil {
		t.Fatal(err)
	}
	if rep.Changed || rep.Written || rep.Created || len(f.writes) != 0 || len(rep.Added)+len(rep.Removed) != 0 {
		t.Errorf("a second apply must be a no-op: %+v, writes %v", rep, f.writes)
	}
}

