func TestApplyDNSRefusesWhenTheJoinHasErrors(t *testing.T) {
	stacks := load(t)
	edit(t, stacks, resolve.KindInstance, "sso", func(r *resolve.Resource) { setConfig(r, "user.tink.role", "") })
	f := platformFiles()
	_, err := ApplyDNS(f, Build(stacks), ApplyOptions{})
	if err == nil || !strings.Contains(err.Error(), "nothing was applied") {
		t.Fatalf("err = %v", err)
	}
	if len(f.reads) != 0 || len(f.writes) != 0 {
		t.Errorf("an errored join must touch nothing: reads %v writes %v", f.reads, f.writes)
	}
}

func TestApplyDNSRefusesToReplaceTheRecordsWithNoneUnlessAsked(t *testing.T) {
	stacks := load(t)
	stacks[1].Resources = removeKind(removeKind(stacks[1].Resources, resolve.KindPublish, "whoami"), resolve.KindPublish, "whoami-admin")
	res := Build(stacks)
	f := platformFiles()
	f.files["tink/dns/hosts"] = wantFile
	if _, err := ApplyDNS(f, res, ApplyOptions{}); err == nil || !strings.Contains(err.Error(), "no published name") {
		t.Fatalf("err = %v", err)
	}
	if len(f.writes) != 0 {
		t.Error("nothing may be written")
	}
	rep, err := ApplyDNS(f, res, ApplyOptions{AllowEmpty: true})
	if err != nil {
		t.Fatal(err)
	}
	if !rep.Written || strings.Join(rep.Removed, "|") != "192.0.2.231 whoami-admin.home.example.org|192.0.2.231 whoami.home.example.org" {
		t.Errorf("report = %+v", rep)
	}
	if got := f.files["tink/dns/hosts"]; strings.Contains(got, "whoami") || !strings.HasPrefix(got, "# Generated by") {
		t.Errorf("an explicitly empty apply leaves just the note: %q", got)
	}
}

